        function verifyPersistedSchemaAndConfiguration( ...
                testCase,sourcePath,destinationPath,definition, ...
                recordCount,sampleCount)
            groupPath = "/" + definition.groupIdentifier;
            sourceInfo = ncinfo(sourcePath,groupPath);
            destinationInfo = ncinfo(destinationPath,groupPath);
            testCase.verifyEqual(sort(string({destinationInfo.Variables.Name})), ...
                sort(string({sourceInfo.Variables.Name})), ...
                definition.name + " output changed the authored variable set.");
            testCase.verifyEqual(sort(string({destinationInfo.Dimensions.Name})), ...
                sort(string({sourceInfo.Dimensions.Name})), ...
                definition.name + " output changed the authored dimension set.");
            for iDimension = 1:numel(sourceInfo.Dimensions)
                sourceDimension = sourceInfo.Dimensions(iDimension);
