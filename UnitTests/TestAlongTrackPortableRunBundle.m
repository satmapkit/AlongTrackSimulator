        function verifyParityCase(testCase,runner,fixtureFolder,definition)
            sourcePath = fullfile(fixtureFolder, ...
                "matlab-authored-" + definition.name + ".nc");
            request = jsondecode(fileread(fullfile(fixtureFolder, ...
                "matlab-authored-" + definition.name + "-request.json")));
            destinationPath = fullfile(testCase.tempFolder, ...
                definition.name + "-parity-output.nc");
            reportPath = fullfile(testCase.tempFolder, ...
                definition.name + "-parity-report.json");
            request.modelFiles = {char(sourcePath)};
            request.output.destinations.(definition.name) = char(destinationPath);
            request.report = char(reportPath);
            requestPath = fullfile(testCase.tempFolder, ...
                definition.name + "-parity-request.json");
            TestAlongTrackPortableRunBundle.writeText( ...
                requestPath,jsonencode(request,PrettyPrint=true));
            sourceBefore = TestAlongTrackPortableRunBundle.fileBytes(sourcePath);

            command = sprintf('"%s" --request "%s"',runner,requestPath);
            [status,output] = ...
                TestAlongTrackPortableRunBundle.runPortableExecutable(command);
            testCase.assertEqual(status,0,output);
            testCase.verifyEqual(TestAlongTrackPortableRunBundle.fileBytes(sourcePath), ...
                sourceBefore,"The runner mutated the " + definition.name + ...
                " MATLAB-authored source bundle.");

            report = jsondecode(fileread(reportPath));
            testCase.verifyEqual(string(report.status),"complete");
            testCase.verifyEqual(string(report.integrator.id),definition.integrator);
            if definition.integrator == "adaptive-rk23"
                testCase.verifyGreaterThan(report.integrator.denseOutputEvaluationCount,0);
            else
                testCase.verifyEqual(report.integrator.denseOutputEvaluationCount,0);
            end

            ats = AlongTrackSimulator();
            missionTime = 0:30000;
            alongtrack = ats.projectedPointsForMissionWithName( ...
                definition.missionName,Lx=8e6,Ly=8e6,lat0=24,lon0=0, ...
                time=missionTime);
            passes = AlongTrackSimulator.convertAlongTrackStructureToPass(alongtrack);
            triggerTimes = cellfun(@(pass) ...
                pass.t(1) + definition.missionEpochSeconds,passes);
            selected = find(triggerTimes >= definition.initialTime & ...
                triggerTimes <= definition.integrationFinalTime);
            testCase.assertNumElements(selected,1, ...
                "The MATLAB authority did not find exactly one " + ...
                definition.name + " occurrence in the runner interval.");
            pass = passes{selected};
            expectedTriggerTime = triggerTimes(selected);
            expectedTime = reshape(pass.t + definition.missionEpochSeconds,[],1);
            expectedX = reshape(pass.x,[],1);
            expectedY = reshape(pass.y,[],1);

            group = "/" + definition.groupIdentifier + "/";
            actualTriggerTime = ncread(destinationPath,group + "t");
            actualTime = ncread(destinationPath,group + "sample-time");
            actualX = ncread(destinationPath,group + "x");
            actualY = ncread(destinationPath,group + "y");
            [triggerAbsolute,triggerNormalized] = ...
                TestAlongTrackPortableRunBundle.errors( ...
                actualTriggerTime,expectedTriggerTime);
            [timeAbsolute,timeNormalized] = TestAlongTrackPortableRunBundle.errors( ...
                actualTime,expectedTime);
            [xAbsolute,xNormalized] = TestAlongTrackPortableRunBundle.errors( ...
                actualX,expectedX);
            [yAbsolute,yNormalized] = TestAlongTrackPortableRunBundle.errors( ...
                actualY,expectedY);

            parityModel = TestAlongTrackPortableRunBundle.fixtureModelAtOccurrence( ...
                definition,expectedTriggerTime);
            [expectedSSH,expectedSSU,expectedSSV] = ...
                parityModel.wvt.variableAtPositionWithName( ...
                reshape(pass.x,1,[]),reshape(pass.y,1,[]),[], ...
                'ssh','ssu','ssv', ...
                interpolationMethod=char(definition.interpolation));
            actualSSH = ncread(destinationPath,group + "ssh");
            actualSSU = ncread(destinationPath,group + "ssu");
            actualSSV = ncread(destinationPath,group + "ssv");
            [sshAbsolute,sshNormalized] = TestAlongTrackPortableRunBundle.errors( ...
                actualSSH,reshape(expectedSSH,[],1));
            [ssuAbsolute,ssuNormalized] = TestAlongTrackPortableRunBundle.errors( ...
                actualSSU,reshape(expectedSSU,[],1));
            [ssvAbsolute,ssvNormalized] = TestAlongTrackPortableRunBundle.errors( ...
                actualSSV,reshape(expectedSSV,[],1));

            absoluteMaxima = [triggerAbsolute,timeAbsolute,xAbsolute,yAbsolute, ...
                sshAbsolute,ssuAbsolute,ssvAbsolute];
            normalizedMaxima = [triggerNormalized,timeNormalized,xNormalized,yNormalized, ...
                sshNormalized,ssuNormalized,ssvNormalized];
            testCase.verifyLessThanOrEqual(normalizedMaxima,1e-12);
            testCase.verifyEqual(ncread(destinationPath, ...
                group + "repeat-cycle-index"),int64(0));
            testCase.verifyEqual(ncread(destinationPath, ...
                group + "first-sample-index"),int64(pass.t(1)));
            testCase.verifyEqual(ncread(destinationPath, ...
                group + "sample-count"),int64(numel(expectedTime)));
            TestAlongTrackPortableRunBundle.verifyPersistedSchemaAndConfiguration( ...
                testCase,sourcePath,destinationPath,definition,1,numel(expectedTime));
            fprintf("ATS4_PARITY %s absolute=[%s] normalized=[%s]\n", ...
                definition.name, ...
                strjoin(compose('%.17g',absoluteMaxima),','), ...
                strjoin(compose('%.17g',normalizedMaxima),','));

            created = TestAlongTrackPortableRunBundle.persistedValues( ...
                destinationPath,group);
            future = find(triggerTimes > definition.integrationFinalTime,1);
            testCase.assertNotEmpty(future, ...
                "The MATLAB authority did not find a later " + ...
                definition.name + " occurrence for restart parity.");
            laterPass = passes{future};
            laterTriggerTime = triggerTimes(future);
            appendRequest = request;
            appendRequest.modelFiles = {char(destinationPath)};
            appendRequest.integration.finalTime = laterTriggerTime;
            appendRequest.output.policy = 'append';
            appendRequest.output.destinations = struct();
            appendReportPath = fullfile(testCase.tempFolder, ...
                definition.name + "-append-report.json");
            appendRequest.report = char(appendReportPath);
            appendRequestPath = fullfile(testCase.tempFolder, ...
                definition.name + "-append-request.json");
            TestAlongTrackPortableRunBundle.writeText( ...
                appendRequestPath,jsonencode(appendRequest,PrettyPrint=true));

            appendCommand = sprintf('"%s" --request "%s"', ...
                runner,appendRequestPath);
            [appendStatus,appendOutput] = ...
                TestAlongTrackPortableRunBundle.runPortableExecutable(appendCommand);
            testCase.assertEqual(appendStatus,0,appendOutput);
            testCase.verifyEqual( ...
                TestAlongTrackPortableRunBundle.fileBytes(sourcePath), ...
                sourceBefore,"Append/restart mutated the " + definition.name + ...
                " MATLAB-authored source bundle.");
            appendReport = jsondecode(fileread(appendReportPath));
            testCase.verifyEqual(string(appendReport.status),"complete");
            testCase.verifyEqual(string(appendReport.integrator.id), ...
                definition.integrator);

            appended = TestAlongTrackPortableRunBundle.persistedValues( ...
                destinationPath,group);
            testCase.assertNumElements(appended.triggerTime,2);
            testCase.verifyEqual(appended.triggerTime(1),created.triggerTime);
            testCase.verifyEqual(appended.scheduleOrdinal,int64([0;1]));
            testCase.verifyEqual(appended.scheduleCursor(1), ...
                created.scheduleCursor);
            testCase.verifyNotEqual(appended.scheduleCursor(2), ...
                appended.scheduleCursor(1));
            testCase.verifyGreaterThan(strlength(appended.scheduleCursor(2)),0);
            testCase.verifyEqual(appended.sampleTime(1:numel(created.sampleTime)), ...
                created.sampleTime);
            testCase.verifyEqual(appended.x(1:numel(created.x)),created.x);
            testCase.verifyEqual(appended.y(1:numel(created.y)),created.y);
            testCase.verifyEqual(appended.ssh(1:numel(created.ssh)),created.ssh);
            testCase.verifyEqual(appended.ssu(1:numel(created.ssu)),created.ssu);
            testCase.verifyEqual(appended.ssv(1:numel(created.ssv)),created.ssv);

            laterSampleCount = numel(laterPass.t);
            laterStart = numel(created.sampleTime) + 1;
            laterIndices = laterStart:(laterStart + laterSampleCount - 1);
            laterExpectedTime = reshape( ...
                laterPass.t + definition.missionEpochSeconds,[],1);
            laterExpectedX = reshape(laterPass.x,[],1);
            laterExpectedY = reshape(laterPass.y,[],1);
            [laterTriggerAbsolute,laterTriggerNormalized] = ...
                TestAlongTrackPortableRunBundle.errors( ...
                appended.triggerTime(2),laterTriggerTime);
            [laterTimeAbsolute,laterTimeNormalized] = ...
                TestAlongTrackPortableRunBundle.errors( ...
                appended.sampleTime(laterIndices),laterExpectedTime);
            [laterXAbsolute,laterXNormalized] = ...
                TestAlongTrackPortableRunBundle.errors( ...
                appended.x(laterIndices),laterExpectedX);
            [laterYAbsolute,laterYNormalized] = ...
                TestAlongTrackPortableRunBundle.errors( ...
                appended.y(laterIndices),laterExpectedY);

            laterModel = ...
                TestAlongTrackPortableRunBundle.fixtureModelAfterContinuation( ...
                definition,laterTriggerTime);
            [laterExpectedSSH,laterExpectedSSU,laterExpectedSSV] = ...
                laterModel.wvt.variableAtPositionWithName( ...
                reshape(laterPass.x,1,[]),reshape(laterPass.y,1,[]),[], ...
                'ssh','ssu','ssv', ...
                interpolationMethod=char(definition.interpolation));
            [laterSSHAbsolute,laterSSHNormalized] = ...
                TestAlongTrackPortableRunBundle.errors( ...
                appended.ssh(laterIndices),reshape(laterExpectedSSH,[],1));
            [laterSSUAbsolute,laterSSUNormalized] = ...
                TestAlongTrackPortableRunBundle.errors( ...
                appended.ssu(laterIndices),reshape(laterExpectedSSU,[],1));
            [laterSSVAbsolute,laterSSVNormalized] = ...
                TestAlongTrackPortableRunBundle.errors( ...
                appended.ssv(laterIndices),reshape(laterExpectedSSV,[],1));

            laterAbsoluteMaxima = [laterTriggerAbsolute,laterTimeAbsolute, ...
                laterXAbsolute,laterYAbsolute,laterSSHAbsolute, ...
                laterSSUAbsolute,laterSSVAbsolute];
            laterNormalizedMaxima = [laterTriggerNormalized, ...
                laterTimeNormalized,laterXNormalized,laterYNormalized, ...
