                model,sourcePath,"j3",initialTime=0,integrationFinalTime=100.5, ...
                finalTime=10000,missionEpochSeconds=-21678, ...
                sampleIntervalSeconds=1,checkpointIntervalSeconds=100.5, ...
                fieldNames=["ssh","ssu","ssv"],interpolation="spline", ...
