        function model = fixtureModelAtOccurrence(definition,occurrenceTime)
            model = TestAlongTrackPortableRunBundle.fixtureModel();
            if definition.integrator ~= "adaptive-rk23"
                if occurrenceTime ~= model.t
                    error("AlongTrackSimulator:UnsupportedParityIntegrator", ...
                        "The fixed parity fixture must occur at its exact initial state.");
                end
                return
            end
            model.setupIntegrator(integratorType='adaptive',integrator=@ode23, ...
                absTolerance=definition.absoluteToleranceScale, ...
                relTolerance=definition.relativeTolerance);
            odeOptions = odeset(model.odeOptions, ...
                'InitialStep',definition.initialStep, ...
                'MaxStep',definition.maximumStep,'OutputFcn',[]);
            model.wvt.restoreForcingAmplitudes();
            requestedTimes = [definition.initialTime occurrenceTime ...
                definition.integrationFinalTime];
            [times,states] = ode23(@(time,state) model.fluxArray(time,state), ...
                requestedTimes,model.initialConditionsArray,odeOptions);
            occurrenceIndex = find(times == occurrenceTime,1);
            if isempty(occurrenceIndex)
                error("AlongTrackSimulator:MissingMATLABParityOccurrence", ...
                    "MATLAB ode23 did not return the requested occurrence time.");
            end
            model.updateIntegratorValuesFromArray( ...
                times(occurrenceIndex),states(occurrenceIndex,:).');
        end

        function model = fixtureModelAfterContinuation(definition,occurrenceTime)
            model = TestAlongTrackPortableRunBundle.fixtureModel();
            segmentTimes = [definition.integrationFinalTime occurrenceTime];
            if definition.integrator == "fixed-rk4"
                model.wvt.restoreForcingAmplitudes();
                state = model.initialConditionsCellArray();
                currentTime = definition.initialTime;
                for segmentTime = segmentTimes
                    wholeStepFinalTime = currentTime + definition.initialStep* ...
                        floor((segmentTime-currentTime)/definition.initialStep);
                    if wholeStepFinalTime > currentTime
                        integrator = WVArrayIntegrator( ...
                            @(time,value) model.fluxAtTimeCellArray(time,value), ...
                            [currentTime wholeStepFinalTime],state, ...
                            definition.initialStep);
                        state = integrator.currentY;
                        currentTime = wholeStepFinalTime;
                    end
                    if currentTime < segmentTime
                        integrator = WVArrayIntegrator( ...
                            @(time,value) model.fluxAtTimeCellArray(time,value), ...
                            [currentTime segmentTime],state, ...
                            segmentTime-currentTime);
                        state = integrator.currentY;
                        currentTime = segmentTime;
                    end
                    model.updateIntegratorValuesFromCellArray(currentTime,state);
                end
                return
            end

            model.setupIntegrator(integratorType='adaptive',integrator=@ode23, ...
                absTolerance=definition.absoluteToleranceScale, ...
                relTolerance=definition.relativeTolerance);
            odeOptions = odeset(model.odeOptions, ...
                'InitialStep',definition.initialStep, ...
                'MaxStep',definition.maximumStep,'OutputFcn',[]);
            model.wvt.restoreForcingAmplitudes();
            for segmentTime = segmentTimes
                [times,states] = ode23( ...
                    @(time,state) model.fluxArray(time,state), ...
                    [model.t segmentTime],model.initialConditionsArray,odeOptions);
                model.updateIntegratorValuesFromArray( ...
                    times(end),states(end,:).');
            end
        end

