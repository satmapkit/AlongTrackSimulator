        function verifyAttributesEqual(testCase,source,destination,context)
            if isempty(source) || isempty(destination)
                testCase.verifyEqual(isempty(destination),isempty(source), ...
                    context + " attributes changed.");
                return
            end
            testCase.verifyEqual(sort(string({destination.Name})), ...
                sort(string({source.Name})),context + " attributes changed.");
            for iAttribute = 1:numel(source)
                destinationAttribute = destination( ...
                    strcmp({destination.Name},source(iAttribute).Name));
                testCase.assertNumElements(destinationAttribute,1);
                testCase.verifyEqual(destinationAttribute.Value,source(iAttribute).Value, ...
                    context + " attribute " + string(source(iAttribute).Name) + ...
                    " changed.");
            end
        end

