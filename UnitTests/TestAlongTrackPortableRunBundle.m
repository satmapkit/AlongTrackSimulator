            rng(271828,'twister');
            wvt = WVTransformConstantStratification([8e6 8e6 500],[8 8 5], ...
                N0=5.2e-3,latitude=24,isHydrostatic=true,shouldAntialias=false);
            wvt.initWithRandomFlow(uvMax=1e-3);
            wvt.addForcing(WVAdaptiveDamping(wvt));
            model = WVModel(wvt);
        end

        function lengthValue = dimensionLength(path,groupPath,name)
            info = ncinfo(path,groupPath);
            dimension = info.Dimensions(strcmp({info.Dimensions.Name},name));
            lengthValue = dimension.Length;
        end

        function bytes = fileBytes(path)
            fileID = fopen(path,'rb');
            if fileID == -1
                error("AlongTrackSimulator:TestFileOpenFailed", ...
                    "Could not open '%s'.",path);
            end
            cleanup = onCleanup(@() fclose(fileID));
            bytes = fread(fileID,Inf,'*uint8');
            clear cleanup
        end

        function writeText(path,text)
            fileID = fopen(path,'wt');
            if fileID == -1
                error("AlongTrackSimulator:TestFileOpenFailed", ...
                    "Could not open '%s'.",path);
            end
            cleanup = onCleanup(@() fclose(fileID));
            fprintf(fileID,'%s',text);
            clear cleanup
        end

        function [status,output] = runPortableExecutable(command)
            if isunix && ~ismac
                originalLibraryPath = getenv('LD_LIBRARY_PATH');
                libraryPathCleanup = onCleanup( ...
                    @() setenv('LD_LIBRARY_PATH',originalLibraryPath));
                setenv('LD_LIBRARY_PATH','');
            end
            [status,output] = system(command);
            if exist('libraryPathCleanup','var')
                clear libraryPathCleanup
            end
        end

        function [absoluteMaximum,normalizedMaximum] = errors(actual,expected)
            delta = abs(double(actual(:))-double(expected(:)));
            absoluteMaximum = max(delta,[],'all');
            normalizedMaximum = absoluteMaximum/max(1,max(abs(double(expected)),[],'all'));
        end
