            restartTimes = ncread(destinationPath,"/portable-restart/t");
            checkpointInitialTime = ncread(destinationPath, ...
                "/portable-restart/initialTime");
            checkpointInterval = ncread(destinationPath, ...
                "/portable-restart/outputInterval");
            expectedCheckpointTime = checkpointInitialTime + ...
