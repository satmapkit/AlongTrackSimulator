        function retainedAuthoringStorageIsDurationIndependent(testCase)
            for missionName = ["j3","alg"]
                shortModel = TestAlongTrackPortableRunBundle.fixtureModel();
                longModel = TestAlongTrackPortableRunBundle.fixtureModel();
                shortStem = missionName + "-short";
                longStem = missionName + "-long";
                shortBundle = authorAlongTrackPortableRunBundle( ...
                    shortModel,fullfile(testCase.tempFolder,shortStem + ".nc"), ...
                    missionName,finalTime=1000,integrationFinalTime=100, ...
                    requestPath=fullfile(testCase.tempFolder,shortStem + ".json"));
                longBundle = authorAlongTrackPortableRunBundle( ...
                    longModel,fullfile(testCase.tempFolder,longStem + ".nc"), ...
                    missionName,finalTime=10*365*86400,integrationFinalTime=100, ...
                    requestPath=fullfile(testCase.tempFolder,longStem + ".json"));

                shortInfo = dir(shortBundle.modelFile);
                longInfo = dir(longBundle.modelFile);
                testCase.verifyEqual(shortInfo.bytes,longInfo.bytes, ...
                    missionName + " authoring storage grew with duration.");
                groupPath = "/" + missionName + "-along-track-output";
                for dimensionName = ["t","sample"]
                    testCase.verifyEqual( ...
                        TestAlongTrackPortableRunBundle.dimensionLength( ...
                        shortBundle.modelFile,groupPath,dimensionName),0);
                    testCase.verifyEqual( ...
                        TestAlongTrackPortableRunBundle.dimensionLength( ...
                        longBundle.modelFile,groupPath,dimensionName),0);
                end
                for attributeName = ["portableScheduleConfiguration", ...
                        "portableObserverConfiguration", ...
                        "portableObservationSchemaManifest"]
                    if attributeName == "portableScheduleConfiguration"
                        attributePath = groupPath;
                    else
                        attributePath = groupPath + ...
                            "/observingSystems/observingSystems-1";
                    end
                    shortAttribute = ncreadatt( ...
                        shortBundle.modelFile,attributePath,attributeName);
                    longAttribute = ncreadatt( ...
                        longBundle.modelFile,attributePath,attributeName);
                    testCase.verifyEqual(string(shortAttribute), ...
                        string(longAttribute), ...
                        missionName + " retained record size grew with duration.");
                end
            end
        end

        function authoringFailurePreservesExistingFiles(testCase)
            model = TestAlongTrackPortableRunBundle.fixtureModel();
            sourcePath = fullfile(testCase.tempFolder,"protected.nc");
            TestAlongTrackPortableRunBundle.writeText(sourcePath,"protected source");
            before = TestAlongTrackPortableRunBundle.fileBytes(sourcePath);
            testCase.verifyError(@() authorAlongTrackPortableRunBundle( ...
                model,sourcePath,"j3",finalTime=100), ...
                "AlongTrackSimulator:PortableAuthoringTargetExists");
            testCase.verifyEqual(TestAlongTrackPortableRunBundle.fileBytes(sourcePath),before);

            destinationPath = fullfile(testCase.tempFolder,"protected-output.nc");
            TestAlongTrackPortableRunBundle.writeText(destinationPath,"protected destination");
            destinationBefore = TestAlongTrackPortableRunBundle.fileBytes(destinationPath);
            testCase.verifyError(@() authorAlongTrackPortableRunBundle( ...
                model,fullfile(testCase.tempFolder,"new.nc"),"j3", ...
                finalTime=100,destinationPath=destinationPath), ...
                "AlongTrackSimulator:PortableDestinationExists");
            testCase.verifyEqual(TestAlongTrackPortableRunBundle.fileBytes(destinationPath), ...
                destinationBefore);
        end

        function extendedRunnerMatchesAuthoritativeMATLAB(testCase)
            runner = string(getenv('ATS4_EXTENDED_RUNNER'));
            testCase.assumeNotEmpty(runner, ...
                "Set ATS4_EXTENDED_RUNNER to run the MATLAB/C++ parity gate.");
            testCase.assertTrue(isfile(runner),"ATS4_EXTENDED_RUNNER does not exist.");

            repositoryRoot = fileparts(fileparts(mfilename('fullpath')));
            fixtureFolder = fullfile(repositoryRoot,"cpp","tests","data","ats4");
            definitions = TestAlongTrackPortableRunBundle.parityDefinitions();
            for iDefinition = 1:numel(definitions)
                TestAlongTrackPortableRunBundle.verifyParityCase( ...
                    testCase,runner,fixtureFolder,definitions(iDefinition));
            end
        end
    end

